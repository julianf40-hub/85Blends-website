#!/usr/bin/env node
// Generates supabase/seed.sql for the LOCAL stack from the prototype's fictional data.
//   node _admin-prototype/backend/tools/make-seed.mjs
// Fictional users only (example.test). The password is a local-only test value, never used anywhere else.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const USERS = {
  publisher: { id: '00000000-0000-4000-8000-0000000000a1', email: 'publisher@example.test', role: 'publisher' },
  editor: { id: '00000000-0000-4000-8000-0000000000a2', email: 'editor@example.test', role: 'editor' },
  outsider: { id: '00000000-0000-4000-8000-0000000000a3', email: 'outsider@example.test', role: null },
  spare: { id: '00000000-0000-4000-8000-0000000000a4', email: 'spare@example.test', role: null },
};
export const LOCAL_TEST_PASSWORD = 'local-only-fictional-password';

const root = new URL('..', import.meta.url);
const draft = JSON.parse(readFileSync(new URL('../data/fictional-draft.json', root)));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

let sql = `-- GENERATED by tools/make-seed.mjs: fictional local data only. Do not edit by hand.\n\n`;
for (const u of Object.values(USERS)) {
  sql += `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, recovery_token, email_change_token_new, email_change)
values ('00000000-0000-0000-0000-000000000000', ${q(u.id)}, 'authenticated', 'authenticated', ${q(u.email)},
  extensions.crypt(${q(LOCAL_TEST_PASSWORD)}, extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(u.id)}, ${q(u.id)}, jsonb_build_object('sub', ${q(u.id)}, 'email', ${q(u.email)}, 'email_verified', true), 'email', now(), now(), now());\n`;
  if (u.role) sql += `insert into public.gear_admins (user_id, role) values (${q(u.id)}, ${q(u.role)});\n`;
  sql += '\n';
}
// Local step-up window, kept equal to GEAR_PRODUCTION_STEP_UP_SECONDS in config.toml (40 s, so the
// expiry test runs quickly). Production would use the migration default of 900 s.
export const LOCAL_STEP_UP_SECONDS = 40;
sql += `update public.gear_settings set production_step_up_seconds = ${LOCAL_STEP_UP_SECONDS};\n`;
sql += `insert into public.gear_catalog_drafts (id, catalog, meta, version) values ('main', ${q(JSON.stringify(draft.catalog))}::jsonb, ${q(JSON.stringify(draft.meta))}::jsonb, 1);\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('supabase/seed.sql', root), sql);
  console.log('wrote supabase/seed.sql');
}
