#!/usr/bin/env node
// Compares the schema inventory of the development history with the deployment package's and writes a
// Markdown report. Every difference is classified: "superseded" (an object of the old Storage path,
// expected to be absent from the package) or UNEXPECTED (must be explained or fixed).
//   node tools/compare-inventories.mjs dev.json package.json > deploy/schema-comparison.md
import { readFileSync } from 'node:fs';

const [dev, pkg] = process.argv.slice(2).map((f) => JSON.parse(readFileSync(f, 'utf8')));
// Objects of the superseded Storage path (and their remnants in shared tables) that the package omits.
const SUPERSEDED = /lease|write_grant|drift|prepare_write|authorize_write|consume_write|gear_record_|object_target|catalog_write_allowed|catalog_version_matches|expected_object|commit_guard|gear_find_intent|'refused'|'recorded'|'verified'|'uncertain'|'conflict'/;
// Package-side differences that are deliberate, with the reason shown in the report.
const EXPLAINED = [
  [/gear_publication_status CHECK \(\(status = 'committed'::text\)\)/, 'the package allows only the status the current design writes; development also lists the superseded upload statuses'],
  [/gear_publication_head authenticated SELECT$/, 'development grants SELECT per column to hide the superseded lease columns; the package has no lease columns, so a table grant is equivalent'],
  [/gear catalog origin read/, 'read policy for the superseded catalog objects; nothing in the current design reads them'],
];
const explain = (k) => EXPLAINED.find(([re]) => re.test(k))?.[1];
// Identity of an object without the parts that may legitimately differ in a comparison.
const identity = { functions: (s) => s.replace(/ src:.*$/, ''), policies: (s) => s.replace(/ using:.*$/, ''), columns: (s) => s, constraints: (s) => s, triggers: (s) => s, tableGrants: (s) => s };

let unexpected = 0;
const lines = ['# Schema comparison: development history vs deployment package', '',
  'Generated by `tools/check-deploy-package.sh` (`tools/schema-inventory.mjs`, `tools/compare-inventories.mjs`) on local stacks.',
  'Development: all migrations in `supabase/migrations/`. Package: only `deploy/package/migrations/`.', ''];
for (const kind of Object.keys(identity)) {
  const d = new Map(dev[kind].map((s) => [identity[kind](s), s]));
  const p = new Map(pkg[kind].map((s) => [identity[kind](s), s]));
  const onlyDev = [...d.keys()].filter((k) => !p.has(k));
  const onlyPkg = [...p.keys()].filter((k) => !d.has(k));
  const changed = [...d.keys()].filter((k) => p.has(k) && d.get(k) !== p.get(k));
  lines.push(`## ${kind} (development ${d.size}, package ${p.size})`, '');
  if (!onlyDev.length && !onlyPkg.length && !changed.length) { lines.push('Identical.', ''); continue; }
  for (const k of onlyDev) {
    const why = SUPERSEDED.test(k) ? 'superseded Storage path; expected' : explain(k);
    if (!why) unexpected += 1;
    lines.push(`- only in development: \`${k}\` ${why ? `(${why})` : '**UNEXPECTED**'}`);
  }
  for (const k of onlyPkg) {
    const why = explain(k);
    if (!why) unexpected += 1;
    lines.push(`- only in package: \`${k}\` ${why ? `(deliberate: ${why})` : '**UNEXPECTED**'}`);
  }
  for (const k of changed) {
    const ok = SUPERSEDED.test(d.get(k)) && !SUPERSEDED.test(p.get(k));
    if (!ok) unexpected += 1;
    lines.push(`- differs: \`${k}\`${ok ? ' (development still lists superseded values; expected)' : ' **UNEXPECTED**'}`,
      `  - development: \`${d.get(k).slice(k.length).trim() || d.get(k)}\``, `  - package: \`${p.get(k).slice(k.length).trim() || p.get(k)}\``);
  }
  lines.push('');
}
lines.splice(5, 0, unexpected ? `**${unexpected} unexpected difference(s).**` : '**No unexpected differences.** Each difference is either part of the superseded Storage path or a deliberate change, with its reason below.', '');
process.stdout.write(lines.join('\n') + '\n');
process.exitCode = unexpected ? 1 : 0;
